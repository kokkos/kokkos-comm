#pragma once

#include <mpi.h>

inline int reduce(int localErrs) {
  int globalErrs = 0;
  int rank       = 0;
  int size       = 0;
  MPI_Comm_rank(MPI_COMM_WORLD, &rank);
  MPI_Comm_size(MPI_COMM_WORLD, &size);
  MPI_Reduce(&localErrs, &globalErrs, 1, MPI_INT, MPI_SUM, 0, MPI_COMM_WORLD);
  return globalErrs;
}